int	ft_is_prime(int nb)
{
	long	a;

	a = 0;
	a = nb;
	if (nb < 2 || nb > 2147483646)
	{
		return (0);
	}
	else
	{
		while (--nb != 1)
		{
			if (a % nb == 0)
			{
				return (0);
			}
		}
		return (1);
	}
}
